const fs = require("fs");
const commandLineArguments = require("minimist")(process.argv.slice(2));
const readFile = require("./src/readFile");
const executeQuery = require("./src/executeQuery");

// The IDE and the grader keep root's password in DB_CREDENTIAL_FILE and run
// `npm run seed:data` without arguments.
const readRootPassword = () =>
  process.env.DB_CREDENTIAL_FILE
    ? fs.readFileSync(process.env.DB_CREDENTIAL_FILE, "utf8").trim()
    : undefined;

(async () => {
  try {
    const sql = await readFile(
      `${require("path").resolve(__dirname)}/seed.sql`
    );
    
    /**
     * Command : npm run seed:data [-- --username= --password=]
     * Note: To be executed with root permissions only; defaults to root with
     * the password from DB_CREDENTIAL_FILE
     * Reads the seed.sql file
     * Splits it with `;` to separate out individual queries
     * Executes individual queries against the DB.
     */
    let result;
    const username = commandLineArguments.username || "root";
    const password = commandLineArguments.password || readRootPassword();
    if (sql.length > 0) {
      const queries = sql.split(";");
      for (const query of queries) {
        if (query.length > 1) {
          result = await executeQuery(query, username, password);
          console.log(result);
        }
      }
      console.log(`Completed executing seed data. You may now proceed with the tasks.`);
    }
  } catch (e) {
    console.error(e);
  }
})();
